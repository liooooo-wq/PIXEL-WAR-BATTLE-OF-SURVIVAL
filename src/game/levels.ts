type RawObstacle = Omit<Obstacle, 'id' | 'hitFlash'>;

function wall(x: number, y: number, w: number, h: number): RawObstacle {
  return { x, y, w, h, type: 'wall', hp: 9999, maxHp: 9999, destructible: false };
}

function building(x: number, y: number, w: number, h: number): RawObstacle {
  return { x, y, w, h, type: 'building', hp: 9999, maxHp: 9999, destructible: false };
}

function sandbag(x: number, y: number, w = 52, h = 24): RawObstacle {
  return { x, y, w, h, type: 'sandbag', hp: 160, maxHp: 160, destructible: true };
}

function crate(x: number, y: number, size = 34): RawObstacle {
  return { x, y, w: size, h: size, type: 'crate', hp: 65, maxHp: 65, destructible: true };
}

function barrel(x: number, y: number): RawObstacle {
  return { x, y, w: 26, h: 26, type: 'barrel', hp: 35, maxHp: 35, destructible: true };
}

